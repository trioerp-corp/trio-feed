def key_for_activity(business, activity):
    """The guide of a shop from its business type and its activity (core/activities.py profile)."""
    from core.activities import APPAREL

    act = activity if isinstance(activity, dict) else {}
    if act.get("key") == "pharmacy":
        return "pharmacy"
    if act.get("key") in APPAREL:
        return "clothes"
    return business if business in KEYS else "market"


def key_for(s):
    """Which guide a shop gets."""
    return key_for_activity(s.business, s.activity)


