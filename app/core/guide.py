def key_for(s):
    """Which guide a shop gets (the pharmacy is a «retail» business with its own guide)."""
    act = s.activity if isinstance(s.activity, dict) else {}
    if act.get("key") == "pharmacy":
        return "pharmacy"
    return s.business if s.business in KEYS else "market"


